import os
from pptx import Presentation
from pptx.util import Inches, Pt
from typing import List, Dict

class PptGenerator:
    """
    Handles the creation of a PowerPoint presentation (.pptx) from extracted 
    video frames and transcribed text segments.
    """

    def __init__(self):
        pass

    def generate_ppt(self, title: str, segments: List[Dict], slides_data: List[Dict], output_path: str) -> str:
        """
        Generates a PowerPoint presentation.
        
        Args:
            title (str): Title of the presentation.
            segments (List[Dict]): Whisper transcription segments.
            slides_data (List[Dict]): List of extracted frames with their timestamps.
            output_path (str): The desired path for the output .pptx file.
            
        Returns:
            str: Path to the generated PPTX file.
        """
        print(f"Generating PowerPoint presentation: {output_path}...")
        try:
            prs = Presentation()
            
            # 1. Create Title Slide
            title_slide_layout = prs.slide_layouts[0] # 0 is typically the title slide layout
            slide = prs.slides.add_slide(title_slide_layout)
            title_box = slide.shapes.title
            subtitle_box = slide.placeholders[1]
            
            title_box.text = title
            subtitle_box.text = "Generated by Video to Markdown & PPT Converter\nGoogle Antigravity"
            
            # 2. Iterate through captured frames (slides_data)
            # layout 5 is typically "Title Only" or a blank layout with a title
            content_slide_layout = prs.slide_layouts[5] 
            
            for i, slide_info in enumerate(slides_data):
                img_path = slide_info['path']
                start_time = slide_info['time_sec']
                
                # Determine end time for this slide (either next slide's time, or end of video)
                if i + 1 < len(slides_data):
                    end_time_for_slide = slides_data[i+1]['time_sec']
                else:
                    # If it's the last slide, capture all remaining text
                    end_time_for_slide = float('inf') 
                
                # Gather all text spoken during this slide's duration
                slide_text = ""
                for seg in segments:
                    if seg['start'] >= start_time and seg['start'] < end_time_for_slide:
                        slide_text += seg['text'].strip() + " "
                
                # Create the actual slide in the PPT
                ppt_slide = prs.slides.add_slide(content_slide_layout)
                
                # Set slide title to the timestamp
                if ppt_slide.shapes.title:
                    ppt_slide.shapes.title.text = f"Timestamp: {self._format_time(start_time)}"
                
                # Add the image (Left side or Full width top)
                if os.path.exists(img_path):
                    # Position image: left=1 inch, top=1.5 inches, width=4 inches (approx half screen)
                    left = Inches(0.5)
                    top = Inches(1.5)
                    width = Inches(4.5)
                    ppt_slide.shapes.add_picture(img_path, left, top, width=width)
                
                # Add the text box for the transcription (Right side)
                left_tb = Inches(5.2)
                top_tb = Inches(1.5)
                width_tb = Inches(4.3)
                height_tb = Inches(5)
                
                txBox = ppt_slide.shapes.add_textbox(left_tb, top_tb, width_tb, height_tb)
                tf = txBox.text_frame
                tf.word_wrap = True
                p = tf.add_paragraph()
                p.text = slide_text.strip() if slide_text.strip() else "(No narration detected for this slide)"
                p.font.size = Pt(14)
            
            # 3. Save the presentation
            output_dir = os.path.dirname(output_path)
            if output_dir and not os.path.exists(output_dir):
                os.makedirs(output_dir)
                
            prs.save(output_path)
            print(f"PowerPoint successfully generated: {output_path}")
            return output_path
            
        except Exception as e:
            print(f"Failed to generate PowerPoint: {e}")
            import traceback
            traceback.print_exc()
            return None

    def _format_time(self, seconds: float) -> str:
        """Helper to format seconds into HH:MM:SS"""
        h = int(seconds // 3600)
        m = int((seconds % 3600) // 60)
        s = int(seconds % 60)
        if h > 0:
            return f"{h:02d}:{m:02d}:{s:02d}"
        return f"{m:02d}:{s:02d}"
